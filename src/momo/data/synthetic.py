"""SYNTHETIC TEST FIXTURE - not a data source, not a back-test input.

This module writes *made-up* market data in the real NSE file layouts so that
the code can be tested without network access and against a known answer.

    !!  Nothing produced from this fixture is a result.  !!
    !!  Never put a number or chart from it in a report. !!

Why it exists
-------------
* The parsers, the corporate-action logic, the identity chaining and the
  back-test accounting can each be checked against the "truth" the generator
  knows (the true total return of every stock on every day).
* It contains, on purpose, every awkward case the real data has: splits,
  bonuses, dividends, rights, a demerger, renames, ISIN changes, a re-used
  symbol, delistings, suspensions, trade-for-trade series, circuit-locked days,
  non-trading days, ETFs and bond lines mixed into the equity series.

The pipeline stamps every output made from it as synthetic
(``DataConfig.data_kind == "synthetic"``).
"""

