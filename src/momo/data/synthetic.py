@dataclass
class FixtureSpec:
    start: dt.date = dt.date(2021, 1, 4)
    end: dt.date = dt.date(2025, 6, 30)  # spans the legacy -> UDiFF switch (8 July 2024)
    n_companies: int = 320
    seed: int = 7
    # How the "exchange" fills PREVCLOSE on an ex-date. Real NSE files are believed to
    # carry the adjusted base price; the pipeline is tested under both conventions.
    prevclose_adjusted: bool = True
    momentum_strength: float = 1.0  # 0 = no momentum effect in the simulated returns
    crash_start: Optional[dt.date] = dt.date(2022, 2, 21)  # a sharp market fall, for stress-test code
    layout: str = "raw"  # "raw": data/raw layout; "server": URL layout (to test the downloader)
    # Index buckets as (name, first rank, last rank) by market cap; scaled to the small fixture.
    index_buckets: List[tuple] = field(default_factory=lambda: [
        ("Nifty 50", 1, 30), ("NIFTY MIDCAP 150", 31, 90), ("NIFTY SMALLCAP 250", 91, 180),
        ("NIFTY MICROCAP 250", 181, 260), ("Nifty 500", 1, 180),
    ])


@dataclass
class FixtureTruth:
    """What the generator knows to be true - used by the tests as the answer key."""

    returns: pd.DataFrame  # date, company, symbol, ret_total, kind ("" | "demerger" | "resume")
    actions: pd.DataFrame  # company, symbol, ex_date, kind, factor, dividend
    companies: pd.DataFrame  # company, symbols, sector, list_date, delist_date, delist_reason
    spec: FixtureSpec


class _Rng:
    """Random numbers that are identical on every NumPy version.

    NumPy's modern ``Generator`` may change its streams between releases; the
    legacy ``RandomState`` is frozen by policy. The fixture must be the same on
    every machine (tests compare against it), so it uses the frozen one, behind
    the handful of method names the generator below needs.
    """

    def __init__(self, seed: int):
        self._rs = np.random.RandomState(seed)

    def random(self, size=None):
        return self._rs.random_sample(size)

    def standard_normal(self, size=None):
        return self._rs.standard_normal(size)

    def normal(self, loc=0.0, scale=1.0, size=None):
        return self._rs.normal(loc, scale, size)

    def uniform(self, low=0.0, high=1.0, size=None):
        return self._rs.uniform(low, high, size)

    def integers(self, low, high, size=None):
        return self._rs.randint(low, high, size)

    def standard_t(self, df, size=None):
        return self._rs.standard_t(df, size)

    def choice(self, a, size=None, replace=True, p=None):
        if isinstance(a, (list, tuple)) and a and isinstance(a[0], (list, tuple)):
            return a[self._rs.randint(0, len(a))]  # pick one tuple from a list of tuples
        return self._rs.choice(a, size=size, replace=replace, p=p)


def _tick(x: np.ndarray) -> np.ndarray:
    return np.round(np.round(np.asarray(x, float) / 0.05) * 0.05, 2)


def _trading_days(start: dt.date, end: dt.date, rng: "_Rng") -> pd.DatetimeIndex:
    days = pd.bdate_range(start, end)
    holidays = set()
    for year in range(start.year, end.year + 1):
        in_year = days[days.year == year]
        if len(in_year) > 40:
            picked = rng.choice(len(in_year), size=min(12, len(in_year) // 20), replace=False)
            holidays |= {in_year[int(k)] for k in picked}
    keep = [d for d in days if d not in holidays]
    if pd.Timestamp(UDIFF_SWITCH_DATE) not in keep and start <= UDIFF_SWITCH_DATE <= end:
        keep.append(pd.Timestamp(UDIFF_SWITCH_DATE))
    return pd.DatetimeIndex(sorted(keep))


def _isin(company: int, serial: int) -> str:
    return f"INE{company:04d}01{serial:02d}0"


def generate_fixture(root: Path, spec: Optional[FixtureSpec] = None) -> FixtureTruth:
    """Write a complete synthetic raw-data tree under ``root`` and return the truth."""
    spec = spec or FixtureSpec()
    rng = _Rng(spec.seed)
    root = Path(root)
    raw = root / ("raw" if spec.layout == "raw" else "server")
    raw.mkdir(parents=True, exist_ok=True)
    (root / "SYNTHETIC_DATA_README.txt").write_text(README_TEXT)

    days = _trading_days(spec.start, spec.end, rng)
    T, N = len(days), spec.n_companies

    # ------------------------------------------------------------------ companies
    sector = rng.integers(0, len(SECTORS), N)
    beta = rng.normal(1.0, 0.25, N).clip(0.4, 1.8)
    idio = rng.uniform(0.012, 0.032, N)
    mcap0 = np.exp(rng.normal(np.log(4e10), 1.6, N)).clip(1.5e9, 3e12)  # rupees
    price0 = _tick(rng.uniform(25, 2500, N))
    shares = np.round(mcap0 / price0)
    fv = rng.choice([10.0, 10.0, 5.0, 2.0, 1.0], N)
    band = rng.choice([0.05, 0.10, 0.20], N, p=[0.15, 0.25, 0.60])
    turnover = np.exp(rng.normal(np.log(0.0015), 0.8, N)).clip(1e-4, 0.02)  # share of mcap traded daily
    size_rank = pd.Series(mcap0).rank(ascending=False).to_numpy()
    no_trade_p = np.where(size_rank > 0.75 * N, rng.uniform(0.0, 0.08, N), 0.0)
    small_tilt = (size_rank / N - 0.5)  # exposure to the small-minus-big factor

    symbol = np.array([f"SYN{i:04d}" for i in range(N)], dtype=object)
    serial = np.ones(N, int)
    symbol_history: List[List[str]] = [[s] for s in symbol]

    list_idx = np.zeros(N, int)
    late = rng.random(N) < 0.18
    list_idx[late] = rng.integers(40, max(41, T - 320), late.sum())
    delist_idx = np.full(N, T + 1)
    reason = np.full(N, "", dtype=object)
    going = np.where(rng.random(N) < 0.12)[0]
    for i in going:
        lo = list_idx[i] + 260
        if lo < T - 60:
            delist_idx[i] = rng.integers(lo, T - 60)
            reason[i] = rng.choice(["merger", "distress", "voluntary"], p=[0.45, 0.35, 0.20])

    # A re-used symbol: company N-1 lists late under the symbol of an early delisting.
    reused_from = None
    early = [i for i in going if reason[i] != "" and delist_idx[i] < T - 420 and i != N - 1]
    if early:
        reused_from = int(early[0])
        list_idx[N - 1] = delist_idx[reused_from] + 300
        delist_idx[N - 1] = T + 1
        reason[N - 1] = ""
        symbol[N - 1] = symbol[reused_from]
        symbol_history[N - 1] = [symbol[N - 1]]

    # Suspensions: a few companies stop trading for a stretch and come back.
    susp_start = np.full(N, -1)
    susp_end = np.full(N, -1)
    for i in rng.choice(N, size=max(2, N // 60), replace=False):
        a = rng.integers(list_idx[i] + 120, max(list_idx[i] + 121, T - 200))
        if a + 150 < min(delist_idx[i], T):
            susp_start[i], susp_end[i] = a, a + rng.integers(25, 110)

    # Trade-for-trade spells (series BE) and one long-term BZ name.
    be_start = np.full(N, -1)
    be_end = np.full(N, -1)
    for i in rng.choice(N, size=max(3, N // 25), replace=False):
        a = rng.integers(list_idx[i] + 60, max(list_idx[i] + 61, T - 120))
        be_start[i], be_end[i] = a, a + rng.integers(20, 90)

    # ------------------------------------------------------------------ corporate actions
    events: Dict[int, List[dict]] = {}
    listings: List[dict] = []  # daily Bc rows

    def add_event(i: int, t: int, kind: str, **kw) -> None:
        if not (list_idx[i] + 30 < t < min(delist_idx[i], T) - 5):
            return
        if susp_start[i] - 3 <= t <= susp_end[i] + 3:
            return
        events.setdefault(t, []).append({"i": int(i), "kind": kind, **kw})

    def mid_sample_day() -> int:
        """A random day away from both ends of the sample (also valid for very short samples)."""
        lo = min(60, T // 3)
        return int(rng.integers(lo, max(T - 20, lo + 1)))

    for i in range(N):
        for year_start in range(0, T, 250):  # dividends: up to two a year for most companies
            if rng.random() < 0.75:
                add_event(i, year_start + rng.integers(20, 240), "dividend", yield_=rng.uniform(0.003, 0.02),
                          as_pct=bool(rng.random() < 0.1))
            if rng.random() < 0.25:
                add_event(i, year_start + rng.integers(20, 240), "dividend", yield_=rng.uniform(0.002, 0.01),
                          as_pct=False)
        if rng.random() < 0.16:
            a, b = [(1, 1), (1, 2), (2, 1), (3, 2), (1, 5)][rng.integers(0, 5)]
            add_event(i, mid_sample_day(), "bonus", a=a, b=b)
        if rng.random() < 0.14 and fv[i] >= 2:
            new = {10.0: [5.0, 2.0, 1.0], 5.0: [1.0], 2.0: [1.0]}[fv[i]]
            add_event(i, mid_sample_day(), "split", new_fv=float(rng.choice(new)))
        if rng.random() < 0.04:
            add_event(i, mid_sample_day(), "rights", a=1, b=int(rng.choice([3, 4, 5])),
                      discount=rng.uniform(0.25, 0.5))
        if rng.random() < 0.015:
            add_event(i, mid_sample_day(), "demerger", spin=rng.uniform(0.2, 0.35))
    for t in list(events):  # one structural event per company per day keeps the truth simple
        seen = set()
        events[t] = [e for e in events[t] if not (e["i"] in seen or seen.add(e["i"]))]

    # Renames: same ISIN, new symbol.
    renames: Dict[int, List[int]] = {}
    for i in rng.choice(N - 1, size=max(3, N // 30), replace=False):
        t = rng.integers(list_idx[i] + 80, max(list_idx[i] + 81, T - 80))
        if t < min(delist_idx[i], T) and not (susp_start[i] <= t <= susp_end[i]):
            renames.setdefault(int(t), []).append(int(i))
    symbol_change_rows = []
    rename_at = np.full(N, -1)
    for t_r, members in renames.items():
        rename_at[members] = t_r
    symbol0 = symbol.copy()

    def symbol_on(i: int, s: int) -> str:
        """Symbol company ``i`` carried on day index ``s`` (renames append an X)."""
        return symbol0[i] if (rename_at[i] < 0 or s < rename_at[i]) else f"{symbol0[i]}X"

    # ------------------------------------------------------------------ factor paths
    mkt = rng.normal(0.0006, 0.009, T)
    if spec.crash_start is not None:
        c0 = int(np.searchsorted(days, pd.Timestamp(spec.crash_start)))
        if c0 + 45 < T:
            mkt[c0:c0 + 22] -= 0.016  # roughly a 30% fall in a month
            mkt[c0 + 22:c0 + 40] += 0.009  # then a sharp rebound
    smb = rng.normal(0.0001, 0.005, T)
    half = T // 2
    smb[half:half + 160] -= 0.0018  # a drawn-out small-cap correction
    sec_f = rng.normal(0.0, 0.005, (T, len(SECTORS)))
    drift = np.zeros(N)
    phi, sig_mu = 0.995, 0.0007 * spec.momentum_strength

    # ------------------------------------------------------------------ simulate day by day
    prev_close = np.full(N, np.nan)
    last_trade = np.full(N, -1)
    rows_ret: List[pd.DataFrame] = []
    rows_act: List[dict] = []
    idx_level = {name: 1000.0 for name, _, _ in spec.index_buckets}
    prev_mcap = np.full(N, np.nan)
    etf_px = np.array([110.0, 54.0, 251.0])
    pr_pending: List[tuple] = []  # PR zips are written after the loop, once all listings are known

    for t, day in enumerate(days):
        d = day.date()
        # symbol renames effective today
        for i in renames.get(t, []):
            new_symbol = f"{symbol[i]}X"
            symbol_change_rows.append((f"Synthetic Company {i:04d} Limited", symbol[i], new_symbol, d))
            symbol[i] = new_symbol
            symbol_history[i].append(new_symbol)

        active = (list_idx <= t) & (t < delist_idx)
        suspended = (susp_start <= t) & (t <= susp_end)
        first_day = list_idx == t
        resume = (susp_end + 1 == t) & (susp_end >= 0)
        has_event = np.zeros(N, bool)
        for e in events.get(t, []):
            has_event[e["i"]] = True
        trade = active & ~suspended & ((rng.random(N) >= no_trade_p) | first_day | has_event | resume)

        drift = phi * drift + np.sqrt(1 - phi ** 2) * sig_mu * rng.standard_normal(N)
        distress = (reason == "distress") & (delist_idx - t < 150) & (delist_idx - t > 0)
        r_tot = (beta * mkt[t] + small_tilt * 2.0 * smb[t] + sec_f[t, sector] + drift
                 + idio * rng.standard_t(5, N) / 1.29 - 0.006 * distress)

        f = np.ones(N)  # split / bonus / rights price factor on the ex-date
        div = np.zeros(N)
        spin = np.zeros(N)
        kind = np.full(N, "", dtype=object)
        for e in events.get(t, []):
            i = e["i"]
            if not trade[i] or not np.isfinite(prev_close[i]):
                continue
            pc_i = prev_close[i]
            rec = {"company": i, "symbol": symbol[i], "ex_date": day, "kind": e["kind"], "factor": 1.0, "dividend": 0.0}
            if e["kind"] == "dividend":
                amount = max(0.05, round(e["yield_"] * pc_i, 2))
                if e["as_pct"]:  # quoted as % of face value, as in older listings
                    pct = max(1.0, round(amount / fv[i] * 100))
                    amount = round(pct / 100 * fv[i], 2)
                    purpose = f"DIVIDEND-{pct:.0f}%"
                else:
                    purpose = rng.choice([
                        f"DIVIDEND - RS {amount:g} PER SHARE", f"INTERIM DIVIDEND - RS {amount:g} PER SHARE",
                        f"AGM/DIV-RS.{amount:g}/- PER SHARE", f"FINAL DIVIDEND - RS {amount:g} PER SHARE"])
                div[i] = amount
                rec["dividend"] = amount
            elif e["kind"] == "bonus":
                f[i] = e["b"] / (e["a"] + e["b"])
                shares[i] = np.round(shares[i] / f[i])
                purpose = rng.choice([f"BONUS {e['a']}:{e['b']}", f"BONUS ISSUE {e['a']}:{e['b']}"])
                rec["factor"] = f[i]
            elif e["kind"] == "split":
                if e["new_fv"] >= fv[i]:
                    continue
                f[i] = e["new_fv"] / fv[i]
                old_fv, fv[i] = fv[i], e["new_fv"]
                shares[i] = np.round(shares[i] / f[i])
                serial[i] += 1  # a face-value change brings a new ISIN
                unit = lambda v: f"RE {v:g}" if v == 1 else f"RS {v:g}"  # noqa: E731
                purpose = rng.choice([
                    f"FACE VALUE SPLIT (SUB-DIVISION) - FROM {unit(old_fv)}/- PER SHARE TO {unit(fv[i])}/- PER SHARE",
                    f"FV SPLIT RS.{old_fv:g}/- TO RS.{fv[i]:g}/-"])
                rec["factor"] = f[i]
            elif e["kind"] == "rights":
                issue = max(fv[i], round(pc_i * (1 - e["discount"]), 0))
                premium = issue - fv[i]
                terp = (e["b"] * pc_i + e["a"] * issue) / (e["a"] + e["b"])
                f[i] = terp / pc_i
                shares[i] = np.round(shares[i] * (e["a"] + e["b"]) / e["b"])
                purpose = f"RIGHTS {e['a']}:{e['b']} @ PREMIUM RS {premium:g}/-"
                rec["factor"] = f[i]
            else:  # demerger
                spin[i] = e["spin"]
                purpose = rng.choice(["DEMERGER", "SCHEME OF ARRANGEMENT"])
                rec["factor"] = 1 - e["spin"]
            kind[i] = e["kind"] if e["kind"] in ("demerger",) else ""
            rows_act.append(rec)
            # Listed daily from announcement to the ex-date; one bonus is first mis-stated then corrected.
            announce = max(0, t - int(rng.integers(8, 18)))
            wrong = e["kind"] == "bonus" and rng.random() < 0.3
            for s in range(announce, t + 1):
                text = purpose
                if wrong and s < t - 4:
                    text = f"BONUS {e['a'] + 1}:{e['b']}"
                listings.append({"seen": s, "series": "EQ", "symbol": symbol_on(i, s), "ex": day,
                                 "purpose": text, "security": f"SYNTHETIC COMPANY {i:04d}"})

        base = prev_close * f
        with np.errstate(invalid="ignore", divide="ignore"):
            r_px = r_tot - div / base - spin
            gap = np.where(resume, rng.uniform(-0.45, 0.2, N), 0.0)  # suspended stocks reopen with a gap
            target = base * (1 + r_px + gap)
            up = np.floor(base * (1 + band) / 0.05 + 1e-9) * 0.05
            dn = np.ceil(base * (1 - band) / 0.05 - 1e-9) * 0.05
        banded = trade & ~first_day & ~resume & (spin == 0)
        close = _tick(target)
        lock = np.zeros(N, int)
        lock[banded & (target >= up)] = 1
        lock[banded & (target <= dn)] = -1
        close = np.where(banded, np.clip(close, _tick(dn), _tick(up)), close)
        close = np.where(first_day, _tick(price0 * (1 + rng.normal(0, 0.08, N))), close)
        close = np.maximum(close, 0.05)

        pc_field = np.where(first_day, price0, prev_close)
        if spec.prevclose_adjusted:
            pc_field = np.where(first_day, price0, np.round(prev_close * f, 2))

        # OHLC consistent with the band and with any circuit lock
        ref = np.where(np.isfinite(base), base, close)
        opn = _tick(ref * (1 + rng.normal(0, 0.004, N)))
        hi = _tick(np.maximum(opn, close) * (1 + np.abs(rng.normal(0, 0.006, N))))
        lo = _tick(np.minimum(opn, close) * (1 - np.abs(rng.normal(0, 0.006, N))))
        hi = np.where(banded, np.minimum(hi, _tick(up)), hi)
        lo = np.where(banded, np.maximum(lo, _tick(dn)), lo)
        hi = np.where(lock == 1, close, np.maximum(hi, close))
        lo = np.where(lock == -1, close, np.minimum(lo, close))
        opn = np.clip(opn, lo, hi)
        vwap = (hi + lo + 2 * close) / 4

        mcap = close * shares
        value = mcap * turnover * np.exp(rng.normal(0, 0.6, N)) * (1 + 4 * np.abs(np.nan_to_num(r_px + gap)))
        value = np.where(lock != 0, value * 0.12, value)  # a locked stock barely trades
        volume = np.maximum(1, np.round(value / vwap))
        value = volume * vwap
        ser = np.where((be_start <= t) & (t <= be_end), "BE", "EQ").astype(object)
        ser[(reason == "distress") & (delist_idx - t < 60)] = "BZ"

        # --- truth ---------------------------------------------------------------------
        with np.errstate(invalid="ignore", divide="ignore"):
            true_ret = (close + div) / (prev_close * f * (1 - spin)) - 1
        ok = trade & np.isfinite(prev_close)
        rows_ret.append(pd.DataFrame({
            "date": day, "company": np.where(ok)[0], "symbol": symbol[ok], "ret_total": true_ret[ok],
            "kind": np.where(resume[ok], "resume", kind[ok]),
        }))

        # --- cash-market bhavcopy ----------------------------------------------------------
        isins = np.array([_isin(i, serial[i]) for i in range(N)], dtype=object)
        etf_px = _tick(etf_px * (1 + mkt[t] + rng.normal(0, 0.001, 3)))
        _write_bhav(raw, spec, d, symbol[trade], ser[trade], isins[trade], opn[trade], hi[trade], lo[trade],
                    close[trade], pc_field[trade], volume[trade], value[trade], etf_px)

        # --- PR zip: corporate actions, market cap, band hits ---------------------------------
        listed = active
        last_trade = np.where(trade, t, last_trade)
        pr_pending.append((d, symbol[listed], ser[listed], np.where(listed)[0], fv[listed],
                           shares[listed], np.where(trade, close, prev_close)[listed], last_trade[listed],
                           symbol[trade & (lock != 0)], ser[trade & (lock != 0)], lock[trade & (lock != 0)]))

        # --- index snapshot -------------------------------------------------------------------------
        with np.errstate(invalid="ignore", divide="ignore"):
            px_ret = np.where(ok, close / (prev_close * f * (1 - spin)) - 1, np.nan)
        rank = pd.Series(np.where(active, prev_mcap, np.nan)).rank(ascending=False).to_numpy()
        ind_rows = []
        for name, r0, r1 in spec.index_buckets:
            member = (rank >= r0) & (rank <= r1) & np.isfinite(px_ret)
            r = float(np.sum(prev_mcap[member] * px_ret[member]) / np.sum(prev_mcap[member])) if member.any() else 0.0
            old = idx_level[name]
            idx_level[name] = old * (1 + r)
            ind_rows.append((name, old, idx_level[name], r))
        _write_ind(raw, spec, d, ind_rows, vix=14 + 900 * abs(mkt[t]) + rng.uniform(0, 3))

        prev_close = np.where(trade, close, prev_close)
        prev_mcap = np.where(active, np.where(np.isfinite(prev_close), prev_close * shares, np.nan), np.nan)

    # ------------------------------------------------------------------ PR zips (deferred)
    by_seen: Dict[int, List[dict]] = {}
    for r in listings:
        by_seen.setdefault(r["seen"], []).append(r)
    for t, (d, *rest) in enumerate(pr_pending):
        _write_pr(raw, spec, d, days, by_seen.get(t, []), *rest)

    # ------------------------------------------------------------------ static + external files
    static_dir = raw / ("static" if spec.layout == "raw" else "content/equities")
    static_dir.mkdir(parents=True, exist_ok=True)
    sc = pd.DataFrame(symbol_change_rows, columns=["name", "old", "new", "date"])
    sc["date"] = [f"{x:%d-%b-%Y}".upper() for x in sc["date"]]
    # the real file starts with a header row; the parser recognises and skips it
    sc.to_csv(static_dir / "symbolchange.csv", index=False,
              header=["SYMB_COMPANY_NAME", " SM_KEY_SYMBOL", " SM_NEW_SYMBOL", " SM_APPLICABLE_FROM"])

    ext = root / "external"
    ext.mkdir(exist_ok=True)
    weeks = pd.date_range(days[0] - pd.Timedelta(days=14), days[-1], freq="7D")
    y = 6.0 + np.cumsum(rng.normal(0, 0.03, len(weeks)))
    pd.DataFrame({"date": weeks.strftime("%Y-%m-%d"), "yield_pct": np.round(y.clip(3.0, 9.0), 2)}).to_csv(
        ext / "risk_free.csv", index=False)
    comp = pd.DataFrame({
        "company": np.arange(N),
        "symbols": ["|".join(h) for h in symbol_history],
        "sector": [SECTORS[k] for k in sector],
        "list_date": [days[min(i, T - 1)] for i in list_idx],
        "delist_date": [days[i - 1] if i <= T else pd.NaT for i in delist_idx],
        "delist_reason": reason,
    })
    sector_rows = [{"symbol": s, "sector": row.sector} for row in comp.itertuples() for s in row.symbols.split("|")]
    pd.DataFrame(sector_rows).drop_duplicates("symbol").to_csv(ext / "sector_map.csv", index=False)
    gone = comp[comp["delist_reason"] != ""]
    pd.DataFrame({
        "symbol": [s.split("|")[-1] for s in gone["symbols"]],
        "terminal_return": gone["delist_reason"].map({"merger": 0.0, "voluntary": 0.05, "distress": -0.8}),
        "reason": gone["delist_reason"],
    }).to_csv(ext / "delistings.csv", index=False)

    truth = FixtureTruth(
        returns=pd.concat(rows_ret, ignore_index=True),
        actions=pd.DataFrame(rows_act),
        companies=comp,
        spec=spec,
    )
    truth.returns.to_parquet(root / "truth_returns.parquet", index=False)
    truth.actions.to_parquet(root / "truth_actions.parquet", index=False)
    truth.companies.to_parquet(root / "truth_companies.parquet", index=False)
    return truth


